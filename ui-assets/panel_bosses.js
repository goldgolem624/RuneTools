  function bossField(vp, t) {
    if (!t) return 0;
    const w = t[2] - t[1] + 1, m = w >= 31 ? 0x7FFFFFFF : ((1 << w) - 1);
    return (((vp[t[0]] || 0) >>> 0) >>> t[1]) & m;
  }
  async function fetchBosses(force) {
    if (!bridge() || bossFetching) return;
    const _t = Date.now(); if (!force && _t - bossFetchAt < 2000) return; bossFetchAt = _t;
    bossFetching = true;
    try {
      let vp = {};
      if (bridge().varps) { try { vp = JSON.parse(await bridge().varps(myPid(), BOSS_VARPS.join(','))); } catch (e) {} }
      if (!vp || !Object.keys(vp).length) return;   // empty read -> keep last good (no all-zero flash)
      bossesData = BOSSES.map(b => {
        const k1 = bossField(vp, b.kc) + 60000 * bossField(vp, b.pr);
        const k2 = b.kc2 ? bossField(vp, b.kc2) + 60000 * bossField(vp, b.pr2) : null;
        const logDone = b.log ? !!(((vp[b.log[0]] || 0) >>> b.log[1]) & 1) : null;
        return { ...b, k1, k2, total: k1 + (k2 || 0), logDone };
      });
      await bcLoadCols();
      await bcLoadVarps();
    } finally { bossFetching = false; }
    if (activeTab === 'bosses') renderBosses();
  }
