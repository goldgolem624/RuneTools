  function bcPaintList(box, cols) {
    box.innerHTML = '';
    let done = 0;
    for (const col of cols) {
      const have = col.items.filter(it => bcOwned(it) === true);
      const missing = col.items.filter(it => bcOwned(it) === false);
      const n = have.length, m = col.items.length;
      const complete = m > 0 && n === m;
      if (complete) done++;
      const r = document.createElement('div'); r.className = 'bc-row';
      const nm = document.createElement('div'); nm.className = 'bc-nm';
      const t = document.createElement('div'); t.textContent = col.name; nm.appendChild(t);
      const sb = document.createElement('div'); sb.className = 'bc-sub';
      sb.textContent = complete ? 'Complete' :
        missing.length ? 'Next: ' + missing[0].name + (missing.length > 1 ? ' (+' + (missing.length - 1) + ' more)' : '') : '';
      nm.appendChild(sb);
      r.appendChild(nm);
      const bar = document.createElement('div'); bar.className = 'bc-bar';
      const fill = document.createElement('div'); fill.className = 'bc-fill' + (complete ? ' full' : '');
      fill.style.width = (m > 0 ? Math.round(n * 100 / m) : 0) + '%';
      bar.appendChild(fill); r.appendChild(bar);
      const p = document.createElement('span');
      p.className = 'bc-pill' + (complete ? ' ok' : n > 0 ? ' go' : '');
      p.textContent = n + ' / ' + m;
      r.appendChild(p);
      // Cap each list: an unbounded missing list makes the bubble taller than the window. Missing is
      // what you act on, so it keeps the bigger share; both say how many were elided.
      const tipList = (label, arr, cap) => !arr.length ? '' :
        '\n\n' + label + ' (' + arr.length + '):\n' +
        arr.slice(0, cap).map(d => '  ' + d.name).join('\n') +
        (arr.length > cap ? '\n  ... and ' + (arr.length - cap) + ' more' : '');
      r.dataset.tip = col.name + tipList('Missing', missing, 20) + tipList('Collected', have, 12);
      box.appendChild(r);
    }
    return done;
  }
