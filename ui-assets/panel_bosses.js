  function bcBossOnlyCols() {
    const bossKeys = new Set();
    for (const b of BOSSES) if (b.log) bossKeys.add(b.log[0] + ':' + b.log[1]);
    return bcCols.filter(col => {
      if (col.cat !== 'boss') return false;
      if (!col.doneVb) return true;
      const t = bcVbIndex[col.doneVb];
      return !(t && bossKeys.has(t[0] + ':' + t[1]));
    });
  }
